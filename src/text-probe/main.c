#include "src/bootstrap-api/text.h"
#include "src/bootstrap-api/arena.h"
#include "src/text-probe/cases.h"
static pangu_arena arena;
static pangu_region_allocator allocator;
static pangu_buffer buffer;
static unsigned char encoded[4];
static unsigned char large_input[1048576];
static pangu_u64 encode(pangu_u32 cp)
{
 if(cp<0x80) { encoded[0]=(unsigned char)cp;return 1; }
 if(cp<0x800) { encoded[0]=(unsigned char)(0xc0+cp/64);encoded[1]=(unsigned char)(0x80+cp%64);return 2; }
 if(cp<0x10000) { encoded[0]=(unsigned char)(0xe0+cp/4096);encoded[1]=(unsigned char)(0x80+(cp/64)%64);encoded[2]=(unsigned char)(0x80+cp%64);return 3; }
 encoded[0]=(unsigned char)(0xf0+cp/262144);encoded[1]=(unsigned char)(0x80+(cp/4096)%64);encoded[2]=(unsigned char)(0x80+(cp/64)%64);encoded[3]=(unsigned char)(0x80+cp%64);return 4;
}
static volatile unsigned char fault_sink;
int text_test(const pangu_memory_api *memory,pangu_u64 argc)
{
 if(argc>1) {
  static pangu_mapping mapping;
  if(memory->map(memory->context,4096,&mapping)) return 70;
  volatile unsigned char *bytes=mapping.address;
  fault_sink=bytes[argc==2 ? 4096 : -1];
  return 71; /* Guard verification must fault before reaching this return. */
 }
 pangu_u64 count=99,error=99,cursor=0; pangu_u32 cp=99;
 pangu_text_slice empty;empty.data=(void *)0;empty.length=0;
 if(pangu_text_validate(empty,&count,&error) || count || error || pangu_text_next(empty,&cursor,&cp)!=3 || cp!=99) return 1;
 if(pangu_text_validate(empty,&count,&count)!=1 || pangu_text_next(empty,(void *)0,&cp)!=1) return 2;
 pangu_text_slice bad={(void *)0,1};
 if(pangu_text_validate(bad,&count,&error)!=1) return 3;
 /* All 1,112,064 Unicode scalar values, independent arithmetic encoder. */
 for(pangu_u32 value=0;value<=0x10ffff;value++) {
  if(value>=0xd800 && value<=0xdfff) continue;
  pangu_u64 length=encode(value); pangu_text_slice s={encoded,length};cursor=0;cp=0xffffffff;
  if(pangu_text_next(s,&cursor,&cp) || cursor!=length || cp!=value) return 4;
  if(pangu_text_validate(s,&count,&error) || count!=1 || error!=length) return 5;
  for(pangu_u64 n=1;n<length;n++) {
   s.length=n;cursor=0;cp=99;
   if(pangu_text_next(s,&cursor,&cp)!=12 || cursor || cp!=99) return 6;
  }
 }
 /* Frozen corpus expectations generated by Python's independent strict codec. */
 for(pangu_u64 i=0;i<sizeof(cases)/sizeof(cases[0]);i++) {
  const struct text_case *v=&cases[i]; pangu_text_slice s={v->bytes,v->length};
  if(pangu_text_validate(s,&count,&error)!=v->status || count!=v->count || error!=v->error) return 7;
  cursor=s.length+1;cp=99;
  if(pangu_text_next(s,&cursor,&cp)!=1 || cursor!=s.length+1 || cp!=99) return 8;
 }
 if(pangu_arena_init(&arena,memory,4096) || pangu_arena_allocator(&arena,&allocator) || pangu_buffer_init(&buffer,&allocator,64)) return 9;
 pangu_text_slice mixed={(const unsigned char *)"A\0\xe4\xb8\xad\xf0\x9f\x98\x80",9};
 if(pangu_text_append(&buffer,mixed) || buffer.length!=9) return 10;
 for(pangu_u64 i=0;i<sizeof(large_input);i+=4) {
  large_input[i]='x';large_input[i+1]=0;large_input[i+2]=0xc2;large_input[i+3]=0xa2;
 }
 pangu_text_slice large;large.data=large_input;large.length=sizeof(large_input);
 if(pangu_text_validate(large,&count,&error) || count!=786432 || error!=1048576) return 24;
 large.length--;
 if(pangu_text_validate(large,&count,&error)!=12 || count!=786431 || error!=1048574) return 25;
 large.length++;
 pangu_u64 before_used=arena.used,before_revision=buffer.revision;
 if(pangu_text_append(&buffer,large)!=2 || arena.used!=before_used || buffer.revision!=before_revision || buffer.length!=9) return 26;
 pangu_buffer_borrow view;
 if(pangu_buffer_view(&buffer,&view)) return 11;
 pangu_u64 used=arena.used,revision=buffer.revision,capacity=buffer.capacity;
 pangu_text_slice invalid={(const unsigned char *)"prefix\xed\xa0\x80",9};
 if(pangu_text_append(&buffer,invalid)!=12 || buffer.length!=9 || buffer.revision!=revision || buffer.capacity!=capacity || arena.used!=used || pangu_buffer_view_validate(&view)) return 12;
 pangu_text_slice self={view.data,view.length};
 if(pangu_text_append(&buffer,self) || buffer.length!=18 || pangu_buffer_view_validate(&view)!=10) return 13;
 pangu_text_slice stored={buffer.data,buffer.length};
 if(pangu_text_validate(stored,&count,&error) || count!=8 || error!=18) return 14;
 if(pangu_buffer_clear(&buffer) || pangu_text_append(&buffer,mixed)) return 22;
 used=arena.used;capacity=buffer.capacity;
 for(pangu_u64 iteration=0;iteration<100000;iteration++) {
  if(pangu_buffer_clear(&buffer) || pangu_text_append(&buffer,mixed) || arena.used!=used || buffer.capacity!=capacity || buffer.length!=9) return 23;
 }
 if(pangu_arena_reset(&arena) || pangu_text_append(&buffer,mixed)!=10 || pangu_buffer_dispose(&buffer) || pangu_arena_dispose(&arena)) return 15;
 if(pangu_arena_init(&arena,memory,4096) || pangu_arena_allocator(&arena,&allocator)) return 16;
 void *page;
 if(allocator.allocate(allocator.context,4096,1,&page)) return 17;
 unsigned char *end=(unsigned char *)page+4096;
 for(pangu_u32 lead=0;lead<256;lead++) {
  end[-1]=(unsigned char)lead;
  pangu_text_slice edge;edge.data=end-1;edge.length=1;cursor=0;cp=99;
  pangu_i32 expected=lead<128 ? 0 : 12;
  if(pangu_text_next(edge,&cursor,&cp)!=expected) return 18;
 }
 end[-4]=0xf4;end[-3]=0x8f;end[-2]=0xbf;end[-1]=0xbf;
 for(pangu_u64 n=1;n<=4;n++) {
  pangu_text_slice edge;edge.data=end-4;edge.length=n;cursor=0;cp=99;
  if(pangu_text_next(edge,&cursor,&cp)!=(n==4 ? 0 : 12)) return 19;
 }
 pangu_text_slice at_end;at_end.data=end;at_end.length=0;cursor=0;
 if(pangu_text_next(at_end,&cursor,&cp)!=3 || pangu_text_validate(at_end,&count,&error)) return 20;
 if(pangu_arena_reset(&arena) || pangu_buffer_init(&buffer,&allocator,4096)) return 27;
 large.length=4096;
 if(pangu_text_append(&buffer,large) || buffer.length!=4096 || buffer.capacity!=4096 || arena.used!=4096) return 28;
 if(pangu_buffer_view(&buffer,&view)) return 29;
 used=arena.used;revision=buffer.revision;
 pangu_text_slice one;one.data=(const unsigned char *)"x";one.length=1;
 if(pangu_text_append(&buffer,one)!=2 || arena.used!=used || buffer.revision!=revision || pangu_buffer_view_validate(&view)) return 30;
 pangu_text_slice full_self;full_self.data=view.data;full_self.length=view.length;
 if(pangu_text_append(&buffer,full_self)!=2 || pangu_buffer_view_validate(&view)) return 31;
 for(pangu_u64 i=0;i<4096;i++) if(buffer.data[i]!=large_input[i]) return 32;
 if(pangu_buffer_clear(&buffer) || pangu_text_append(&buffer,large) || arena.used!=used) return 33;
 if(pangu_buffer_dispose(&buffer) || pangu_arena_dispose(&arena)) return 21;
 return 0;
}
